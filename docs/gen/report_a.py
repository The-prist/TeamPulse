            "想统计「这个月研发部谁迟到最多」，得手工在 Excel 里对。",
            "**数据不产生联动。** 考勤系统不知道你在哪个项目组，协作系统不知道你今天几点到，"
            "所以「某项目组因为天天加班导致迟到率上升」这种信息永远看不到。",
