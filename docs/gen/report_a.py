            ["怎么考勤？", "墙上的 ESP32 打卡机按指纹，数据自动进系统"],
            ["怎么知道谁迟到了？", "系统按考勤规则自动算出迟到分钟数，考勤看板实时显示"],
            ["月底怎么出报表？", "考勤是按天汇总存储的，直接查某段时间的汇总即可，不用扫原始打卡记录"],
