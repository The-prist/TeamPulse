    d.p("**C3. 存量明文密码怎么迁移的？**")
    d.p(
        "自定义 `MigratingPasswordEncoder`：matches 时判断是否 BCrypt 开头，不是就按明文比对并返回 true；"
        "`upgradeEncoding` 返回 true 告诉框架需要升级；"
        "再让 `UserDetailsServiceImpl` 实现 `UserDetailsPasswordService`，"
        "Spring Security 在登录成功后自动回调它把 BCrypt 密文写回库。用户完全无感知。"
    )

    d.p("**C4. 为什么不直接把所有密码重置？**")
    d.p(
        "产品上不可接受：员工会因为「莫名其妙要改密码」而抱怨，也会有人根本收不到通知。"
        "技术上也不必要——登录是天然的一次性迁移时机。"
    )

    d.p("**C5. 怎么防止越权改别人的数据？**")
    d.p(
        "三层：① 接口级 `@PreAuthorize` 控制管理端；② 服务级 `requireSelfOrAdmin` 比对数据归属；"
        "③ 当前用户 ID 一律来自 `SecurityUtils`（JWT），**绝不从请求参数取**——"
        "原项目的漏洞正是从请求头取 userId。"
    )

    d.p("**C6. 你的系统有什么已知安全短板？**")
    d.p(
        "主动说出来比被问出来好：① JWT 无法主动吊销；② MQTT 1883 是明文（应上 8883 + TLS）；"
        "③ 登录接口没做失败次数限流（容易被撞库，可以加 Redis 计数）；"
        "④ 设备密钥在数据库里是明文存储（可以加密存储或用 KMS）。"
    )

    d.h3("D. 数据库与性能")
    d.p("**D1. 为什么打卡要两张表？**")
    d.p(
        "`attendance_record` 是事件流（只增不改，保留原始报文用于审计），"
        "`attendance_daily` 是每人每天的预计算汇总。报表直接查汇总表，"
        "把「按天聚合十万行明细」降为「按索引查几百行」，这是典型的空间换时间。"
    )

    d.p("**D2. 汇总什么时候更新？会不会不一致？**")
    d.p(
        "打卡落库后立即重算当天的汇总，所以看板是实时的；另外每天 00:05 定时补一次，"
        "用于覆盖「一次卡都没打」的缺勤人员和接口异常回滚后的修复。"
        "两者都是幂等 upsert（按 user_id + work_date），重复执行不会产生脏数据。"
    )

    d.p("**D3. 列表接口怎么避免 N+1？**")
    d.p(
        "先在 Service 里收集所有关联 ID，用 `selectBatchIds` 或一次 `IN` 查询取回，"
        "再在内存里做 Map 映射。比如打卡记录要显示姓名和设备位置，"
        "一页 10 条只有 3 条 SQL（主查询 + 用户 IN + 设备 IN），与页大小无关。"
    )

    d.p("**D4. 深分页怎么处理？**")
    d.p(
        "目前用 MyBatis-Plus 物理分页并限制 `size <= 500`，足以应对管理后台场景。"
        "如果数据量到百万级，`LIMIT 100000, 10` 会变慢，方案是「延迟关联」"
        "（先用覆盖索引查主键再回表）或改为游标分页（where id > lastId）。"
    )

    d.p("**D5. 索引怎么设计的？**")
    d.p(
        "每条索引都对应一个真实查询：`uk_user_employee_no` 支撑打卡反查用户，"
        "`idx_record_user_date` 支撑个人考勤，`idx_record_date_status` 支撑当天迟到统计。"
        "联合索引遵循「最左前缀 + 区分度高在前」。"
        "反面例子：原项目给 `schedule` 加的索引列顺序和使用场景不匹配，已按查询重排。"
    )

    d.p("**D6. 逻辑删除和唯一索引冲突怎么办？**")
    d.p(
        "会冲突：删除后重新创建同名记录会撞唯一键。本项目的处理是"
        "「用户不做同名重建（走停用）」，团队名则用包含 deleted 行的显式 SQL 检查并翻译成 409。"
        "更通用的方案是把唯一键改成 `(name, deleted)` 或用时间戳填充，但会牺牲语义清晰度。"
    )

    d.h3("E. 前端")
    d.p("**E1. 为什么用轮询而不是 WebSocket？**")
    d.p(
        "打卡是低频事件（一天几百次），5 秒轮询的平均延迟 2.5 秒完全够用；"
        "而 WebSocket 在 Nginx 长连接、内存占用、断线重连上的成本，在 4G 机器上不划算。"
        "如果将来要秒级推送，把接口换成 SSE 即可，页面结构不用改。"
    )

    d.p("**E2. 前端怎么处理 401？**")
    d.p(
        "axios 响应拦截器统一处理：清 token → 整页跳转 /login。"
        "用 `window.location.assign` 而不是 router.push，是为了确保内存里的旧状态和定时器全部销毁，"
        "避免「退出登录后还在轮询」这种诡异现象。"
    )

    d.p("**E3. 路由守卫能当权限用吗？**")
    d.p(
        "不能。它只是体验优化（不让用户看到无权页面），真正的权限在后端 `@PreAuthorize`。"
        "改 localStorage 里的 role 可以绕过前端守卫，但接口仍会返回 403。"
    )

    d.p("**E4. 构建体积怎么优化？**")
    d.p(
        "按依赖变动频率分包（vue / element / echarts 各一块），业务代码单独一块；"
        "配合 Nginx 对 `/assets/` 强缓存一年、`index.html` 不缓存。"
        "这样发版时用户只需重新下载业务代码那一小块。"
    )

    d.h3("F. 部署与运维")
    d.p("**F1. 4G 内存怎么塞下 5 个容器？**")
    d.p(
        "每个容器设内存上限并配套调参：MySQL buffer pool 384M、JVM `-XX:MaxRAMPercentage=70`、"
        "Redis maxmemory 128M、Mosquitto 64M，合计约 2.3G，留 1.5G 给系统。"
        "**能被问出具体数字，说明是真的部署过。**"
    )

    d.p("**F2. 为什么用 Mosquitto 而不是 EMQX？**")
    d.p(
        "EMQX 功能更全（集群、规则引擎、Dashboard），但内存占用是 Mosquitto 的几十倍。"
        "在 4C4G、只有几台打卡机的场景下，Mosquitto 的 10MB 占用才是正确选择。"
        "如果设备数涨到上千或需要集群，再换 EMQX。"
    )

    d.p("**F3. 发布出问题怎么回滚？**")
    d.p(
        "镜像打固定 tag，回滚就是改 tag 重启；涉及数据结构的变更要求「破坏性 DDL 拆成两次发布」"
        "（先加新列兼容旧代码，下个版本再删旧列），因为 Flyway 不支持自动降级。"
    )

    d.p("**F4. 备份怎么做？演练过吗？**")
    d.p(
        "`mysqldump --single-transaction` 每日全量 + 保留 7 天，cron 定时。"
        "恢复命令写在文档里，并且真的演练过一次（恢复后比对 attendance_record 行数）。"
        "**没演练过的备份等于没有备份。**"
    )

